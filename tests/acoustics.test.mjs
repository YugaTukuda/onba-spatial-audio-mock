import assert from 'node:assert/strict';
import { DEFAULT_ROOM, ROOM_PRESETS, normalizeRoom, roomMetrics, reflectedSources, impulseChannels } from '../room-acoustics.js';
import { initialScene, validateScene } from '../scene.js';

const metrics=roomMetrics(DEFAULT_ROOM);
assert.equal(metrics.volume,300);
assert.equal(metrics.surfaceArea,320);
assert.ok(Math.abs(metrics.rt60-.161*300/(-320*Math.log(1-27/320)))<1e-10);
assert.ok(roomMetrics({...DEFAULT_ROOM,wallAbsorption:.6}).rt60<metrics.rt60);
assert.ok(roomMetrics({...DEFAULT_ROOM,height:6}).rt60>metrics.rt60);
assert.equal(roomMetrics({...DEFAULT_ROOM,autoRt60:false,rt60:2.5,wallAbsorption:.9}).rt60,2.5);
assert.equal(roomMetrics({...DEFAULT_ROOM,wallAbsorption:0,floorAbsorption:0,ceilingAbsorption:0}).rt60,6);
assert.ok(roomMetrics(ROOM_PRESETS.concrete).rt60>metrics.rt60);
assert.ok(roomMetrics(ROOM_PRESETS.treated).rt60<metrics.rt60);
const images=reflectedSources({x:2,z:3,height:1.5},DEFAULT_ROOM);
assert.equal(images.length,6);
assert.deepEqual(images.map(p=>[p.x,p.z,p.height]),[[-2,3,1.5],[18,3,1.5],[2,-3,1.5],[2,17,1.5],[2,3,-1.5],[2,3,4.5]]);
assert.equal(images[4].reflection,Math.sqrt(.95));
for(const input of [{height:NaN},{height:1},{wallAbsorption:1},{predelay:101},{autoRt60:'yes'},{preset:'__proto__'}]) assert.throws(()=>normalizeRoom(input));
const scene=initialScene();scene.room={...DEFAULT_ROOM,preset:'custom',autoRt60:false,rt60:2.5,predelay:37};
assert.deepEqual(validateScene(JSON.parse(JSON.stringify(scene))).room,scene.room);
const legacy=structuredClone(scene);delete legacy.room;legacy.sources[0].height=4.5;
assert.equal(validateScene(legacy).sources[0].height,4.5);
assert.ok(validateScene(legacy).room.height>4.5);
const impossible=structuredClone(scene);impossible.sources[0].height=4.5;
assert.throws(()=>validateScene(impossible));
const rate=48000,rt60=1.8,channels=impulseChannels(rate,rt60);
const rmsAt=t=>{const a=channels[0].subarray(Math.round(t*rate),Math.round((t+.04)*rate));return Math.sqrt(a.reduce((sum,n)=>sum+n*n,0)/a.length);};
const slope=20*Math.log10(rmsAt(1.4)/rmsAt(.1))/1.3;
assert.ok(Math.abs(slope-(-60/rt60))<.8,`RT60 decay slope: ${slope}`);
assert.equal(channels[0].length,Math.ceil(rate*rt60*1.15));
assert.notDeepEqual(channels[0],channels[1]);
assert.ok(impulseChannels(rate,3)[0].length>impulseChannels(rate,.6)[0].length*4.9);
console.log(`PASS: Eyring estimate (${metrics.rt60.toFixed(3)}s), six reflections, absorption, RT60 envelope (${slope.toFixed(2)}dB/s), scene roundtrip and legacy compatibility`);
